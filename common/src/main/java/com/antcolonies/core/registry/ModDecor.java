package com.antcolonies.core.registry;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.UnaryOperator;

import com.antcolonies.content.block.DecorClusterBlock;

import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.DoorBlock;
import net.minecraft.world.level.block.RotatedPillarBlock;
import net.minecraft.world.level.block.SlabBlock;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.StairBlock;
import net.minecraft.world.level.block.TransparentBlock;
import net.minecraft.world.level.block.TrapDoorBlock;
import net.minecraft.world.level.block.WallBlock;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.properties.BlockSetType;
import net.minecraft.world.level.material.MapColor;
import net.neoforged.neoforge.registries.DeferredBlock;

/**
 * The nest-building palette: blocks for players who build their own anthills, underground bases and laboratories, made
 * from the mod's own materials. Five families, each with a purpose of its own:
 * <ul>
 *     <li><b>Anthill</b> (earth the ants dig and pack): soil, packed soil, bricks, polished bricks, a pillar.</li>
 *     <li><b>Chitin</b> (from Chitin Plates): a solid block, polished, bricks, tiles.</li>
 *     <li><b>Amber</b> (Ant Resin, which Wood Ants gather, hardened): a block with an ant caught inside, bricks, a see-through
 *     glass and a block reinforced with Chitin.</li>
 *     <li><b>Fungal</b> (from the fungus gardens of Farmer Ants): a block, bricks and a glowing block.</li>
 *     <li><b>Royal</b> (Chitin set with gold and Royal Jelly, for a Queen's chamber): a block, bricks, a pillar and a
 *     chiseled crest.</li>
 * </ul>
 * Besides: a Nest Door and Trapdoor, the Pheromone Lamp, piles of decorative eggs and larvae, and Terrarium Glass.
 * Bricks and polished blocks come with stairs and slabs, bricks with walls as well. Every one is generated by DataGen
 * and TexGen (models, recipes, loot, tags).
 */
public final class ModDecor {
    /** A family's look and feel, shared by its block, stairs, slab and wall. */
    private record Feel(MapColor color, float strength, float resistance, SoundType sound, boolean tool) {
        BlockBehaviour.Properties apply(BlockBehaviour.Properties p) {
            p = p.mapColor(color).strength(strength, resistance).sound(sound);
            return tool ? p.requiresCorrectToolForDrops() : p;
        }
    }

    private static final Feel SOIL = new Feel(MapColor.DIRT, 0.6F, 0.6F, SoundType.ROOTED_DIRT, false);
    private static final Feel PACKED = new Feel(MapColor.TERRACOTTA_BROWN, 1.0F, 3.0F, SoundType.PACKED_MUD, false);
    private static final Feel BRICK = new Feel(MapColor.TERRACOTTA_BROWN, 1.5F, 3.0F, SoundType.MUD_BRICKS, true);
    private static final Feel CHITIN = new Feel(MapColor.COLOR_BROWN, 2.0F, 6.0F, SoundType.BONE_BLOCK, true);
    private static final Feel RESIN = new Feel(MapColor.COLOR_ORANGE, 1.2F, 3.0F, SoundType.HONEY_BLOCK, false);
    private static final Feel FUNGAL = new Feel(MapColor.TERRACOTTA_WHITE, 0.8F, 1.0F, SoundType.FUNGUS, false);
    private static final Feel FUNGAL_BRICK = new Feel(MapColor.TERRACOTTA_WHITE, 1.2F, 3.0F, SoundType.NETHER_WART, false);
    private static final Feel ROYAL = new Feel(MapColor.GOLD, 2.5F, 6.0F, SoundType.BONE_BLOCK, true);

    /** Every decorative block by id, in the order of the creative tab (DataGen and TexGen list the same ids). */
    public static final Map<String, DeferredBlock<? extends Block>> ALL = new LinkedHashMap<>();
    /** The ids of the blocks that have stairs and slabs, and of those that also have walls. */
    public static final List<String> WITH_STAIRS = new ArrayList<>();
    public static final List<String> WITH_WALLS = new ArrayList<>();

    // --- Anthill ---
    public static final DeferredBlock<Block> ANTHILL_SOIL = simple("anthill_soil", SOIL);
    public static final DeferredBlock<Block> PACKED_ANTHILL_SOIL = simple("packed_anthill_soil", PACKED);
    public static final DeferredBlock<Block> ANTHILL_BRICKS = family("anthill_bricks", BRICK, true);
    public static final DeferredBlock<Block> POLISHED_ANTHILL_BRICKS = family("polished_anthill_bricks", BRICK, false);
    public static final DeferredBlock<RotatedPillarBlock> NEST_PILLAR = pillar("nest_pillar", BRICK);
    // --- Chitin ---
    public static final DeferredBlock<Block> CHITIN_BLOCK = simple("chitin_block", CHITIN);
    public static final DeferredBlock<Block> POLISHED_CHITIN = family("polished_chitin", CHITIN, false);
    public static final DeferredBlock<Block> CHITIN_BRICKS = family("chitin_bricks", CHITIN, true);
    public static final DeferredBlock<Block> CHITIN_TILES = family("chitin_tiles", CHITIN, false);
    // --- Amber (Ant Resin, hardened; named so as not to clash with vanilla's Resin Block and Resin Bricks) ---
    public static final DeferredBlock<Block> AMBER_BLOCK = simple("amber_block", RESIN);
    public static final DeferredBlock<Block> AMBER_BRICKS = family("amber_bricks", new Feel(MapColor.COLOR_ORANGE, 1.5F, 3.0F, SoundType.STONE, true), true);
    public static final DeferredBlock<TransparentBlock> AMBER_GLASS = register("amber_glass", TransparentBlock::new,
            p -> p.mapColor(MapColor.COLOR_ORANGE).strength(0.5F).sound(SoundType.GLASS).noOcclusion()
                    .isValidSpawn((state, level, pos, type) -> false).isRedstoneConductor((state, level, pos) -> false)
                    .isSuffocating((state, level, pos) -> false).isViewBlocking((state, level, pos, near) -> false));
    public static final DeferredBlock<Block> REINFORCED_AMBER = register("reinforced_amber", Block::new,
            p -> p.mapColor(MapColor.COLOR_ORANGE).strength(4.0F, 1200.0F).sound(SoundType.STONE).requiresCorrectToolForDrops());
    // --- Fungal ---
    public static final DeferredBlock<Block> FUNGAL_BLOCK = simple("fungal_block", FUNGAL);
    public static final DeferredBlock<Block> FUNGAL_BRICKS = family("fungal_bricks", FUNGAL_BRICK, true);
    public static final DeferredBlock<Block> GLOWING_FUNGAL_BLOCK = register("glowing_fungal_block", Block::new,
            p -> FUNGAL.apply(p).lightLevel(state -> 13));
    // --- Royal ---
    public static final DeferredBlock<Block> ROYAL_CHITIN_BLOCK = simple("royal_chitin_block", ROYAL);
    public static final DeferredBlock<Block> ROYAL_CHITIN_BRICKS = family("royal_chitin_bricks", ROYAL, false);
    public static final DeferredBlock<RotatedPillarBlock> ROYAL_CHITIN_PILLAR = pillar("royal_chitin_pillar", ROYAL);
    public static final DeferredBlock<Block> CHISELED_ROYAL_CHITIN = simple("chiseled_royal_chitin", ROYAL);
    // --- Fittings ---
    public static final DeferredBlock<DoorBlock> NEST_DOOR = register("nest_door", p -> new DoorBlock(BlockSetType.SPRUCE, p),
            p -> p.mapColor(MapColor.COLOR_BROWN).strength(3.0F).sound(SoundType.WOOD).noOcclusion());
    public static final DeferredBlock<TrapDoorBlock> NEST_TRAPDOOR = register("nest_trapdoor", p -> new TrapDoorBlock(BlockSetType.SPRUCE, p),
            p -> p.mapColor(MapColor.COLOR_BROWN).strength(3.0F).sound(SoundType.WOOD).noOcclusion()
                    .isValidSpawn((state, level, pos, type) -> false));
    public static final DeferredBlock<Block> PHEROMONE_LAMP = register("pheromone_lamp", Block::new,
            p -> p.mapColor(MapColor.COLOR_YELLOW).strength(0.6F).sound(SoundType.FROGLIGHT).lightLevel(state -> 15));
    public static final DeferredBlock<DecorClusterBlock> ANT_EGG_CLUSTER = register("ant_egg_cluster", DecorClusterBlock::new,
            p -> p.mapColor(MapColor.TERRACOTTA_WHITE).strength(0.2F).sound(SoundType.FROGSPAWN).noOcclusion());
    public static final DeferredBlock<DecorClusterBlock> LARVA_CLUSTER = register("larva_cluster", DecorClusterBlock::new,
            p -> p.mapColor(MapColor.TERRACOTTA_WHITE).strength(0.2F).sound(SoundType.SLIME_BLOCK).noOcclusion());
    public static final DeferredBlock<TransparentBlock> TERRARIUM_GLASS = register("terrarium_glass", TransparentBlock::new,
            p -> p.mapColor(MapColor.NONE).strength(0.4F).sound(SoundType.GLASS).noOcclusion()
                    .isValidSpawn((state, level, pos, type) -> false).isRedstoneConductor((state, level, pos) -> false)
                    .isSuffocating((state, level, pos) -> false).isViewBlocking((state, level, pos, near) -> false));

    private static <T extends Block> DeferredBlock<T> register(String id, java.util.function.Function<BlockBehaviour.Properties, T> factory,
                                                               UnaryOperator<BlockBehaviour.Properties> properties) {
        DeferredBlock<T> block = ModBlocks.BLOCKS.registerBlock(id, factory, properties);
        ALL.put(id, block);
        return block;
    }

    private static DeferredBlock<Block> simple(String id, Feel feel) {
        return register(id, Block::new, feel::apply);
    }

    private static DeferredBlock<RotatedPillarBlock> pillar(String id, Feel feel) {
        return register(id, RotatedPillarBlock::new, feel::apply);
    }

    /** A block with stairs and a slab (and a wall), named {@code <id minus "s"/"_block">_stairs}, {@code _slab}, {@code _wall}. */
    private static DeferredBlock<Block> family(String id, Feel feel, boolean wall) {
        DeferredBlock<Block> base = simple(id, feel);
        String stem = stem(id);
        WITH_STAIRS.add(id);
        register(stem + "_stairs", p -> new StairBlock(base.get().defaultBlockState(), p), feel::apply);
        register(stem + "_slab", SlabBlock::new, feel::apply);
        if (wall) {
            WITH_WALLS.add(id);
            register(stem + "_wall", WallBlock::new, p -> feel.apply(p).forceSolidOn());
        }
        return base;
    }

    /** The name its stairs, slab and wall start with: "anthill_bricks" gives "anthill_brick", "polished_chitin" stays. */
    public static String stem(String id) {
        return id.endsWith("bricks") || id.endsWith("tiles") ? id.substring(0, id.length() - 1) : id;
    }

    /** Called from {@link ModBlocks} so the class loads with the other blocks. */
    static void init() {
    }

    private ModDecor() {}
}
